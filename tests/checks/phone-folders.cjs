// The two folders on the Home Screen: they open in place, turn pages, open what is picked in its app, and close.
const { chromium } = require('playwright')
const path = require('path')
const base = process.argv[2] || 'http://127.0.0.1:5173/'
;(async () => {
  const browser = await chromium.launch()
  let failed = 0
  const say = (ok, what, detail = '') => { if (!ok) failed++; console.log(`${ok ? 'PASS' : 'FAIL'}  ${what}${detail ? `  (${detail})` : ''}`) }
  const ctx = await browser.newContext({ viewport: { width: 393, height: 760 }, deviceScaleFactor: 2, hasTouch: true, isMobile: true })
  const page = await ctx.newPage()
  const errors = []
  page.on('console', (m) => m.type() === 'error' && errors.push(m.text()))
  page.on('pageerror', (e) => errors.push(String(e)))
  const sleep = (ms) => page.waitForTimeout(ms)
  const st = () => page.evaluate(() => history.state?.shrug)
  const out = (n) => path.join(__dirname, '..', 'audit', 'shots', `flow-${n}.png`)
  await page.goto(base + '?still'); await sleep(1500)
  await page.keyboard.press('Enter'); await sleep(1100)
  const tiles = await page.evaluate(() => [...document.querySelectorAll('.sb-folder')].map((b) => ({ name: b.textContent.trim(), logos: b.querySelectorAll('.logo').length, titles: b.querySelectorAll('.sb-folder__titles span').length })))
  say(tiles.length === 2 && tiles[0].logos === 9 && tiles[1].titles === 3, 'the Home Screen has two folders: nine logos showing through Portfolio, three questions through FAQs', JSON.stringify(tiles))
  await page.locator('.sb-folder').first().tap(); await sleep(900)
  let s = await st()
  const open = await page.evaluate(() => ({ name: document.querySelector('.sb-open__name')?.textContent, apps: document.querySelectorAll('.sb-open__app').length, pages: document.querySelectorAll('.sb-open__page').length, first: [...document.querySelectorAll('.sb-open__page:first-child .sb-icon__name')].map((e) => e.textContent).slice(0, 3), blurred: !!document.querySelector('.sb-home[data-folder]') }))
  say(s.app === null && s.sheet === 'folder:portfolio' && open.name === 'Portfolio' && open.apps === 79 && open.pages === 9 && open.blurred, 'Portfolio opens where it is: 79 companies, nine to a page, in the list’s order', JSON.stringify(open))
  await page.screenshot({ path: out('portfolio') })
  // Turn the page with a swipe
  const box = await page.locator('.sb-open__pages').boundingBox()
  const cdp = await ctx.newCDPSession(page)
  const sw = async (x0, x1, y) => { await cdp.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [{ x: x0, y }] }); for (let i = 1; i <= 8; i++) { await cdp.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [{ x: x0 + ((x1 - x0) * i) / 8, y }] }); await sleep(16) } await cdp.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] }) }
  await sw(box.x + box.width * 0.8, box.x + box.width * 0.15, box.y + box.height / 2); await sleep(900)
  const dot = await page.evaluate(() => [...document.querySelectorAll('.sb-open__dot')].findIndex((d) => d.hasAttribute('data-current')))
  say(dot === 1, 'a swipe turns to the next page', `dot ${dot}`)
  await page.locator('.sb-open__page').nth(1).locator('.sb-open__app', { hasText: 'Superplastic' }).tap(); await sleep(1400)
  s = await st()
  say(s.app === 'finder' && s.stacks.finder.join() === 'co:Superplastic' && s.sheet === null, 'a company opens in Contacts, at its card', JSON.stringify({ app: s.app, stack: s.stacks.finder, sheet: s.sheet }))
  await page.screenshot({ path: out('company') })
  await page.locator('.sb-homebar .sr-only').evaluate((el) => el.click()); await sleep(1100)
  s = await st()
  say(s.app === null && s.sheet === null && !(await page.locator('.sb-open').count()), 'going Home from there is the Home Screen, the folder shut')
  // FAQs
  await page.locator('.sb-folder').nth(1).tap(); await sleep(900)
  s = await st()
  const notes = await page.locator('.sb-open__note').count()
  say(s.sheet === 'folder:faqs' && notes === 10, 'FAQs opens the same way, with the ten questions', `${notes}`)
  await page.screenshot({ path: out('faqs') })
  await page.goBack(); await sleep(800)
  s = await st()
  say(s.sheet === null && !(await page.locator('.sb-open:not([data-closing])').count()), "the browser's back closes a folder")
  await page.locator('.sb-folder').nth(1).tap(); await sleep(900)
  await page.locator('.sb-open__note', { hasText: 'How do you do marketing?' }).tap(); await sleep(1400)
  s = await st()
  say(s.app === 'notes' && s.stacks.notes.join() === 'f:faqs,n:4', 'a question opens as its note in Notes', s.stacks.notes.join())
  await page.locator('.sb-homebar .sr-only').evaluate((el) => el.click()); await sleep(1100)
  // Tap outside, Escape, and the home bar close it too
  await page.locator('.sb-folder').first().tap(); await sleep(800)
  await page.touchscreen.tap(196, 730); await sleep(800)
  say(!(await page.locator('.sb-open:not([data-closing])').count()) && (await st()).sheet === null, 'a tap outside closes it')
  await page.locator('.sb-folder').first().tap(); await sleep(800)
  await page.keyboard.press('Escape'); await sleep(800)
  say(!(await page.locator('.sb-open:not([data-closing])').count()), 'Escape closes it')
  await page.locator('.sb-folder').first().tap(); await sleep(800)
  await page.reload(); await sleep(1600)
  s = await st()
  say(s.sheet === 'folder:portfolio' && (await page.locator('.sb-open__app').count()) === 79, 'a reload comes back to the open folder')
  await page.locator('.sb-homebar .sr-only').evaluate((el) => el.click()); await sleep(900)
  say((await st()).sheet === null, 'and the home bar closes it')
  const seen = [...new Set(errors)].filter((e) => !/Failed to load resource|\[vite\]/.test(e))
  say(seen.length === 0, seen.length ? 'console errors: ' + seen.slice(0, 5).join(' | ') : 'no console errors')
  await browser.close()
  console.log(failed ? `${failed} FAILED` : 'ALL PASS')
})().catch((e) => { console.error('FAILED', e.message.split('\n').slice(0, 6).join('\n')); process.exit(1) })
